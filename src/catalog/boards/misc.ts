import type { Board, BoardCodeMeta } from '../../types'
import { boardDefaults, bp, makeBoard, mcuPins, pw } from '../board-builders'

interface ArmBoardSeed {
  id: string
  name: string
  shortName: string
  vendor: string
  chip: string
  family?: string
  gpio: number[]
  adc?: number[]
  dac?: number[]
  bus?: Parameters<typeof mcuPins>[0]['bus']
  flash: string
  ram: string
  clock: string
  logicVoltage?: number
  inputVoltage?: string
  connectivity?: string[]
  interfaces?: string[]
  formFactor?: string
  description: string
  bestFor?: string[]
  tags?: string[]
  notes?: string[]
  power?: ReturnType<typeof pw>[]
  protocols?: string[]
  industrial?: boolean
  operatingTempC?: [number, number]
  code?: Partial<BoardCodeMeta>
  accent?: string
}

const armBoard = (seed: ArmBoardSeed): Board => {
  const pins = mcuPins({ gpio: seed.gpio, adc: seed.adc, dac: seed.dac, bus: seed.bus })
  const logicVoltage = seed.logicVoltage ?? 3.3
  return makeBoard({
    id: seed.id,
    name: seed.name,
    shortName: seed.shortName,
    vendor: seed.vendor,
    chip: seed.chip,
    family: seed.family ?? 'ARM Cortex-M',
    logicVoltage,
    inputVoltage: seed.inputVoltage ?? '5 V USB',
    flash: seed.flash,
    ram: seed.ram,
    clock: seed.clock,
    gpioCount: seed.gpio.length,
    adcChannels: seed.adc?.length ?? 0,
    dacChannels: seed.dac?.length,
    connectivity: seed.connectivity ?? [],
    interfaces: seed.interfaces ?? ['GPIO', 'ADC', 'PWM', 'I2C', 'SPI', 'UART'],
    formFactor: seed.formFactor ?? 'Dev board',
    description: seed.description,
    bestFor: seed.bestFor ?? [],
    tags: ['arm', `${logicVoltage}v`, ...(seed.tags ?? [])],
    pins,
    powerPins: seed.power ?? [
      pw('vbus', 'VIN / 5V', 5, 1000, 'USB or external 5 V input'),
      pw('3v3', '3.3V', 3.3, 500, 'On-board regulator output'),
      pw('gnd', 'GND', 0, 0),
    ],
    defaults: boardDefaults(seed.bus ?? {}),
    code: { platform: 'arduino', wifi: false, adcBits: 12, ...seed.code },
    notes: seed.notes ?? ['3.3 V logic. Verify the exact pin labels against the board schematic.'],
    accent: seed.accent ?? '#a78bfa',
    protocols: seed.protocols,
    industrial: seed.industrial,
    operatingTempC: seed.operatingTempC,
  })
}

