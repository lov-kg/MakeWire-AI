interface ArmSeed {
  id: string
  name: string
  shortName: string
  vendor?: string
  chip: string
  gpio: number[]
  adc?: number[]
  dac?: number[]
  bus?: Parameters<typeof mcuPins>[0]['bus']
  flash: string
  ram: string
  clock: string
  connectivity?: string[]
  formFactor?: string
  description: string
  bestFor?: string[]
  tags?: string[]
  notes?: string[]
  logicVoltage?: number
  protocols?: string[]
  industrial?: boolean
  operatingTempC?: [number, number]
  code?: Partial<BoardCodeMeta>
  dacChannels?: number
  ledPin?: string
}

const armArduino = (seed: ArmSeed): Board => {
  const bus = seed.bus ?? { sda: 20, scl: 21, sck: 24, mosi: 23, miso: 22, cs: 25, tx: 1, rx: 0 }
  const pins = mcuPins({
    gpio: seed.gpio,
    adc: seed.adc,
    dac: seed.dac,
    bus,
  })
  return makeBoard({
    id: seed.id,
    name: seed.name,
    shortName: seed.shortName,
    vendor: seed.vendor ?? 'Arduino',
    chip: seed.chip,
    family: 'Arduino',
    logicVoltage: seed.logicVoltage ?? 3.3,
    inputVoltage: '5 V USB / VIN',
    flash: seed.flash,
    ram: seed.ram,
    clock: seed.clock,
    gpioCount: seed.gpio.length,
    adcChannels: seed.adc?.length ?? 0,
    dacChannels: seed.dacChannels,
    connectivity: seed.connectivity ?? [],
    interfaces: ['GPIO', 'ADC', 'PWM', 'I2C', 'SPI', 'UART'],
    formFactor: seed.formFactor ?? 'Arduino MKR / Nano',
    description: seed.description,
    bestFor: seed.bestFor ?? [],
    tags: ['arduino', 'arm', '3.3v', ...(seed.tags ?? [])],
    pins,
    powerPins: [
      pw('vin', 'VIN', 5, 800),
      pw('5v', '5V', 5, 500, 'USB or regulator output'),
      pw('3v3', '3.3V', 3.3, 600, 'On-board regulator output'),
      pw('gnd', 'GND', 0, 0),
    ],
    defaults: boardDefaults(bus),
    code: {
      platform: 'arduino',
      wifi: Boolean(seed.connectivity?.some((item) => /wi-fi/i.test(item))),
      adcBits: 12,
      ledPinCode: seed.ledPin,
      ...seed.code,
    },
    notes: [
      '3.3 V logic unless the board has level shifters. Check the exact header labels.',
      ...(seed.notes ?? []),
    ],
    accent: '#22d3ee',
    protocols: seed.protocols,
    industrial: seed.industrial,
    operatingTempC: seed.operatingTempC,
  })
}

