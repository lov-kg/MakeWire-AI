import type { Board, BoardPowerPin } from '../../types'
import { avrBoard, boardDefaults, bp, makeBoard, mcuPins, pw, stm32Board } from '../board-builders'

interface MotionSeed {
  id: string
  name: string
  shortName: string
  vendor: string
  chip: string
  family?: string
  gpio: number[] | string[]
  adc?: number[] | string[]
  bus?: Parameters<typeof mcuPins>[0]['bus']
  flash: string
  ram: string
  clock: string
  description: string
  bestFor?: string[]
  tags?: string[]
  logicVoltage?: number
  inputVoltage?: string
  power: BoardPowerPin[]
  motors?: string
  connectivity?: string[]
  interfaces?: string[]
  formFactor?: string
  notes?: string[]
  protocols?: string[]
  industrial?: boolean
  operatingTempC?: [number, number]
  code?: Parameters<typeof makeBoard>[0]['code']
}

const motionBoard = (seed: MotionSeed): Board => {
  const isString = seed.gpio.length > 0 && typeof seed.gpio[0] === 'string'
  const pins = isString
    ? (seed.gpio as string[]).map((name) => bp(name.toLowerCase(), name, name, ['gpio'], name))
    : mcuPins({
        gpio: seed.gpio as number[],
        adc: seed.adc as number[] | undefined,
        bus: seed.bus,
      })
  return makeBoard({
    id: seed.id,
    name: seed.name,
    shortName: seed.shortName,
    vendor: seed.vendor,
    chip: seed.chip,
    family: seed.family ?? 'Motion Controller',
    logicVoltage: seed.logicVoltage ?? 3.3,
    inputVoltage: seed.inputVoltage ?? '12-24 V DC',
    flash: seed.flash,
    ram: seed.ram,
    clock: seed.clock,
    gpioCount: pins.length,
    adcChannels: Array.isArray(seed.adc) ? seed.adc.length : 0,
    connectivity: seed.connectivity ?? ['USB', 'UART'],
    interfaces: seed.interfaces ?? ['GPIO', 'PWM', 'Step/Dir', 'Endstops', 'Thermistors'],
    formFactor: seed.formFactor ?? 'Controller board',
    description: seed.description,
    bestFor: seed.bestFor ?? [],
    tags: ['robotics', 'motion', ...(seed.tags ?? [])],
    pins,
    powerPins: seed.power,
    defaults: boardDefaults({}),
    code: { platform: 'arduino', wifi: false, adcBits: 12, ...seed.code },
    notes: seed.notes ?? [
      'Motor, heater and solenoid loads must be powered from the dedicated supply, never from the logic rail.',
      'Verify endstop polarity and stepper current limits before the first move.',
    ],
    accent: '#fb923c',
    protocols: seed.protocols,
    industrial: seed.industrial,
    operatingTempC: seed.operatingTempC,
  })
}

