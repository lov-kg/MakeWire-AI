const fieldbusNode = (
  seed: {
    id: string
    name: string
    manufacturer: string
    category: string
    description: string
    protocol: string
    bus: 'rs485' | 'can'
    voltage?: number
    tags: string[]
    safety?: string[]
    industrial?: boolean
  },
): ComponentDefinition =>
  makeComponent({
    id: seed.id,
    name: seed.name,
    manufacturer: seed.manufacturer,
    category: seed.category,
    description: seed.description,
    voltage: seed.voltage ?? 24,
    logicVoltage: 24,
    pins: [
      powerPin('L+'),
      groundPin('M'),
      seed.bus === 'can'
        ? cp('canh', 'CANH', 'can-h', 'bidir', 'CAN high; 120 Ω termination at the trunk ends.', false)
        : cp('a', 'A', 'rs485-a', 'bidir', 'RS-485 A; twisted pair and 120 Ω termination.', false),
      seed.bus === 'can'
        ? cp('canl', 'CANL', 'can-l', 'bidir', 'CAN low; 120 Ω termination at the trunk ends.', false)
        : cp('b', 'B', 'rs485-b', 'bidir', 'RS-485 B; twisted pair and 120 Ω termination.', false),
    ],
    interfaces: [seed.protocol],
    protocols: [seed.protocol],
    requiresExternalSupply: true,
    industrial: true,
    tags: ['fieldbus', seed.bus, ...seed.tags],
    safety: seed.safety ?? [
      'The module is a network slave: connect A/B or CAN H/L with the correct polarity and terminate the trunk.',
      'Use a 24 V supply with overcurrent protection and a common 0 V reference.',
    ],
  })

