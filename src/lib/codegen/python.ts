import {
  baseFilename,
  buildContext,
  detectFeatures,
  makeExplanation,
  makeTitle,
  type CodeDraft,
  type LocalCodeInput,
} from './shared'

const pyValue = (value: string): string => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')

const sanitizeKey = (value: string): string =>
  value
    .replace(/[^a-zA-Z0-9_]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()

/**
 * Python scaffold for Linux SBCs (Raspberry Pi, Jetson, Orange Pi...). The
 * exact header pin codes come from the wiring plan; hardware access is left as
 * explicit stubs because GPIO libraries differ across SBC vendors and kernels.
 */
export function generatePythonCode(input: LocalCodeInput): CodeDraft {
  const ctx = buildContext(input)
  const features = detectFeatures(ctx)
  const title = makeTitle(ctx.prompt, ctx.parts[0]?.def.shortName ?? 'MakerWire')
  const filename = baseFilename(ctx, 'python', title)

  const wiringLines: string[] = []
  for (const part of ctx.parts) {
    wiringLines.push(`    "${pyValue(part.def.shortName)}": {`)
    for (const connection of ctx.plan.connections.filter(
      (item) => item.componentInstanceId === part.item.instanceId,
    )) {
      wiringLines.push(
        `        "${pyValue(connection.componentPinLabel)}": "${pyValue(`${connection.boardPinCode} (${connection.boardPinLabel})`)}",  # ${connection.role}`,
      )
    }
    wiringLines.push('    },')
  }

  const warningLines = ctx.plan.warnings.map(
    (warning) => `# ${warning.severity.toUpperCase()}: ${warning.title} — ${warning.detail}`,
  )

  const i2cSda = ctx.plan.connections.find((connection) => connection.role === 'i2c-sda')
  const i2cScl = ctx.plan.connections.find((connection) => connection.role === 'i2c-scl')
  const gpioLines = ctx.plan.connections
    .filter((connection) => connection.boardPinKind === 'gpio' && !connection.role.startsWith('i2c-'))
    .map(
      (connection) =>
        `#   ${connection.componentLabel} ${connection.componentPinLabel} -> ${connection.boardPinCode} (${connection.boardPinLabel}) [${connection.role}]`,
    )

  const sensorHints = Array.from(new Set(ctx.parts.map((part) => part.def.shortName))).slice(0, 12)

  const code = [
    '#!/usr/bin/env python3',
    `"""${pyValue(title)}`,
    '',
    `Generated by MakerWire AI for ${ctx.board.name} (${ctx.board.chip}) using Python.`,
    `Wiring plan: ${ctx.plan.connections.length} connections, ${ctx.plan.stats.signals} signals.`,
    "Review every pin against your board's header documentation before powering the hardware.",
    '"""',
    '',
    'import time',
    '',
    `BOARD = "${pyValue(ctx.board.name)}"`,
    `BOARD_CHIP = "${pyValue(ctx.board.chip)}"`,
    `LOGIC_VOLTAGE = ${ctx.board.logicVoltage}`,
    `SAMPLE_INTERVAL_S = ${(features.intervalMs / 1000).toFixed(2)}`,
    '',
    '# Exact wiring map produced by the pin engine.',
    '# Board pin codes are header/GPIO references, not bus addresses.',
    'WIRING = {',
    ...wiringLines,
    '}',
    '',
    `I2C_SDA_HEADER = "${pyValue(i2cSda?.boardPinCode ?? 'not assigned')}"`,
    `I2C_SCL_HEADER = "${pyValue(i2cScl?.boardPinCode ?? 'not assigned')}"`,
    '',
    ...warningLines,
    warningLines.length ? '' : '# No safety warnings were raised for this plan.',
    '# GPIO / fieldbus assignments:',
    ...(gpioLines.length ? gpioLines : ['#   (no generic GPIO assignments)']),
    '',
    '',
    'def describe() -> None:',
    '    """Print the bench configuration and the exact wiring map."""',
    `    print(f"MakerWire AI :: {BOARD} ({BOARD_CHIP})")`,
    '    print(f"Logic voltage: {LOGIC_VOLTAGE} V, sample interval: {SAMPLE_INTERVAL_S} s")',
    '    for device, pins in WIRING.items():',
    '        print(f"- {device}")',
    '        for signal, header in pins.items():',
    '            print(f"    {signal:>10} -> {header}")',
    '',
    '',
    'def read_sensors() -> dict[str, float]:',
    '    """Return the latest sensor values.',
    '',
    '    Replace this stub with the driver for your SBC: smbus2 for I2C, spidev for',
    '    SPI, gpiod/gpiozero for GPIO and pyserial for UART. Keep the same keys as',
    '    the wiring map so the sample loop stays readable.',
    '    """',
    '    return {}',
    '',
    '',
    'def apply_outputs(readings: dict[str, float]) -> None:',
    '    """Drive relays, LEDs or actuators from the latest readings."""',
    '    # Example: only switch an output after validating the reading range.',
    '    _ = readings',
    '',
    '',
    'def main() -> None:',
    '    describe()',
    `    print("Known devices: ${pyValue(sensorHints.join(', ') || 'none')}")`,
    '    while True:',
    '        readings = read_sensors()',
    '        apply_outputs(readings)',
    '        if readings:',
    '            print(readings)',
    '        time.sleep(SAMPLE_INTERVAL_S)',
    '',
    '',
    'if __name__ == "__main__":',
    '    try:',
    '        main()',
    '    except KeyboardInterrupt:',
    '        print("\\nStopped.")',
    '',
  ].join('\n')

  return {
    code,
    libraries: [],
    explanation: makeExplanation(ctx, features, [
      'This is a Python scaffold for a Linux SBC. It never bit-bangs pins through sysfs: install the vendor GPIO/I2C/SPI library and fill in the read/apply stubs.',
      'Header pin codes are physical references. Confirm the mapping for your exact board revision and any carrier/hat before connecting hardware.',
    ]),
    filename,
  }
}
