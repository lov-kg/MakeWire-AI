import {
  baseFilename,
  buildContext,
  detectFeatures,
  makeExplanation,
  makeTitle,
  type CodeDraft,
  type LocalCodeInput,
} from './shared'

const stSafe = (value: string): string =>
  value.replace(/[^a-zA-Z0-9_]/g, '_').replace(/^[0-9]/, '_$&').slice(0, 24).toUpperCase()

/**
 * IEC 61131-3 Structured Text scaffold for PLC targets. The generated program
 * exposes the exact field I/O map and a cyclic sampling task. Actual I/O
 * addresses (%I, %Q, %IW...) depend on the PLC's device configuration, so they
 * are documented as comments rather than invented.
 */
export function generateStructuredTextCode(input: LocalCodeInput): CodeDraft {
  const ctx = buildContext(input)
  const features = detectFeatures(ctx)
  const title = makeTitle(ctx.prompt, ctx.parts[0]?.def.shortName ?? 'MakerWire')
  const filename = baseFilename(ctx, 'structured-text', title)

  const variableLines: string[] = []
  const mapLines: string[] = []
  const usedNames = new Set<string>(['ENABLE', 'SAMPLE_TIMER', 'SAMPLE_PULSE'])

  for (const part of ctx.parts) {
    const connections = ctx.plan.connections.filter(
      (connection) => connection.componentInstanceId === part.item.instanceId,
    )
    for (const connection of connections) {
      const base = stSafe(`${part.def.shortName}_${connection.componentPinLabel}`)
      let name = base
      let suffix = 2
      while (usedNames.has(name)) {
        name = `${base}_${suffix}`
        suffix += 1
      }
      usedNames.add(name)
      variableLines.push(
        `    ${name} : BOOL; (* ${part.def.shortName} ${connection.componentPinLabel} -> ${connection.boardPinCode} ${connection.boardPinLabel} [${connection.role}] *)`,
      )
    }
    mapLines.push(`(* ${part.def.shortName} (${part.def.category})`)
    for (const connection of connections) {
      mapLines.push(
        `   ${connection.componentPinLabel} -> ${connection.boardPinCode} (${connection.boardPinLabel}) : ${connection.role}`,
      )
    }
    mapLines.push('*)')
  }

  const warningLines = ctx.plan.warnings.map(
    (warning) => `(* ${warning.severity.toUpperCase()}: ${warning.title} — ${warning.detail} *)`,
  )

  const code = [
    `(* ${title}`,
    '',
    `   Generated by MakerWire AI for ${ctx.board.name} (${ctx.board.chip}).`,
    `   Wiring plan: ${ctx.plan.connections.length} connections, ${ctx.plan.stats.signals} signals.`,
    `   Logic / field voltage: ${ctx.board.logicVoltage} V.`,
    '   Map the symbolic variables below to your PLC device configuration (%I, %Q, %IW, %QW).',
    '   Review the field wiring and safety interlocks with a qualified controls engineer.',
    '*)',
    '',
    'PROGRAM MakerWire',
    'VAR',
    '    ENABLE : BOOL := TRUE;',
    `    SAMPLE_TIMER : TON;`,
    '    SAMPLE_PULSE : BOOL;',
    ...variableLines,
    'END_VAR',
    '',
    ...warningLines,
    warningLines.length ? '' : '(* No safety warnings were raised for this plan. *)',
    '',
    '(* Field I/O map',
    ...mapLines,
    '*)',
    '',
    '(* Cyclic sampling task. Replace the symbolic handlers with your process logic. *)',
    `SAMPLE_TIMER(IN := ENABLE, PT := T#${Math.max(100, features.intervalMs)}MS);`,
    'SAMPLE_PULSE := SAMPLE_TIMER.Q;',
    'IF SAMPLE_TIMER.Q THEN',
    '    SAMPLE_TIMER(IN := FALSE);',
    'END_IF;',
    '',
    'IF SAMPLE_PULSE THEN',
    '    (* TODO: read inputs, apply interlocks, then drive outputs. *)',
    'END_IF;',
    '',
    'END_PROGRAM',
    '',
  ].join('\n')

  return {
    code,
    libraries: [],
    explanation: makeExplanation(ctx, features, [
      'This is an IEC 61131-3 Structured Text scaffold, not a vendor-compiled project. Create the program in your PLC IDE (TIA Portal, Studio 5000, TwinCAT, CODESYS...) and bind the symbolic variables to the physical I/O addresses.',
      'Safety functions, interlocks and emergency stops must be implemented in hardware or in a safety-rated controller — never only in standard application code.',
    ]),
    filename,
  }
}
