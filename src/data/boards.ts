export const getBoard = (id: string | null | undefined): Board | undefined =>
  BOARDS.find((board) => board.id === id)

export const boardGroups = Array.from(new Set(BOARDS.map((board) => board.family)))

export const boardSearchText = (board: Board): string =>
  [
    board.name,
    board.shortName,
    board.vendor,
    board.chip,
    board.family,
    board.description,
    ...board.tags,
    ...board.interfaces,
    ...board.connectivity,
  ]
    .join(' ')
    .toLowerCase()
