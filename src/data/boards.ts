import type {
  Board,
  BoardPin,
  BoardPowerPin,
  PinCapability,
} from '../types'

const p = (
  id: string,
  label: string,
  pinCode: string,
  caps: PinCapability[],
  gpio?: number | string,
  note?: string,
  restricted?: boolean,
  inputOnly?: boolean,
): BoardPin => ({ id, label, pinCode, caps, gpio, note, restricted, inputOnly })

const power = (
  id: string,
  label: string,
  voltage: 0 | 3.3 | 5,
  maxCurrentMa: number,
  note?: string,
): BoardPowerPin => ({ id, label, voltage, maxCurrentMa, note })

const analogPin = (id: string, label: string, pinCode: string, gpio: number, extra: PinCapability[] = []) =>
  p(id, label, pinCode, ['gpio', 'adc', ...extra], gpio)

